// Refreshes src/forest/contributions.ts with the last year of GitHub activity.
// Uses the GitHub CLI's login, so it counts what you see on your own profile
// (private contributions included, as daily totals only).
//
//   npm run contributions
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const query = `query {
  viewer {
    contributionsCollection {
      contributionCalendar {
        weeks { contributionDays { date contributionCount } }
      }
    }
  }
}`;

const raw = execFileSync('gh', ['api', 'graphql', '-f', `query=${query}`], { encoding: 'utf8' });
const days = JSON.parse(raw)
  .data.viewer.contributionsCollection.contributionCalendar.weeks.flatMap((w) => w.contributionDays)
  .sort((a, b) => a.date.localeCompare(b.date));

if (!days.length) throw new Error('GitHub returned no contribution days');

const out = `// Generated by scripts/fetch-contributions.mjs. Do not edit by hand.
// One count per day, starting at \`from\`.
export const CONTRIBUTIONS = {
  from: '${days[0].date}',
  to: '${days[days.length - 1].date}',
  counts: [${days.map((d) => d.contributionCount).join(', ')}],
};
`;

const target = fileURLToPath(new URL('../src/forest/contributions.ts', import.meta.url));
writeFileSync(target, out);
console.log(`Wrote ${days.length} days (${days[0].date} to ${days[days.length - 1].date}) to ${target}`);
